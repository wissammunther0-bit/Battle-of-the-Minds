import { getLang } from './i18n.js';

let usedNames = new Set();

export function pickBotName(flag = 'SA') {
  const lang = getLang();
  const pool = BOT_NAMES[lang] || BOT_NAMES.en;
  const all = [
    ...pool.male.map(n => ({ name: n, gender: 'male' })),
    ...pool.female.map(n => ({ name: n, gender: 'female' }))
  ].filter(x => !usedNames.has(x.name));

  if (!all.length) {
    return { name: 'Bot_' + Math.floor(Math.random() * 9999), gender: 'male', flag };
  }
  const pick = all[Math.floor(Math.random() * all.length)];
  usedNames.add(pick.name);
  return { name: pick.name, gender: pick.gender, flag };
}

export function resetBotNames() {
  usedNames = new Set();
}