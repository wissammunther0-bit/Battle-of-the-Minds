// بعد إزالة ربط الـ 3D (طلب المستخدم: أداء أعلى + خصوصية مطورين)
// أصبحت كل ردود الفعل البصرية DOM/CSS خالصة داخل ArenaStage:
//  - attack(charId): ضربة الفائز — شرر + اندفاع شريط المواجهة
//    + اهتزاز خفيف. تمر منها كل الإجابات الصحيحة (أنا/بوتات/لاعبون).
//  - fallAndRise(): كانت زلزال المشهد ثلاثي الأبعاد — الآن اهتزاز
//    قوي للساحة (يُستخدم عند الأحداث الكبرى).
// ============================================================

export class Animations {
  constructor(engine) {
    this.engine = engine;
  }

  /** 🗡️ ضربة الفائز — تفاعل شريط المواجهة + اهتزاز خفيف للساحة */
  attack(charId) {
    const arena = this.engine.arena;
    if (!arena) return;
    arena.react('win', charId);
    arena.shake(220);
  }

  /** 🥊 الحدث الكبير — اهتزاز قوي (بديل الزلزال القديم) */
  fallAndRise() {
    const arena = this.engine.arena;
    if (!arena) return;
    arena.shake(700);
  }
}
